"""P19: parameter and model recovery for the estimator the transfer test uses.

Why this exists. The recovery analysis of the platform used a summary-statistic
estimator at 500 to 2000 trials. The transfer test uses a different estimator:
trial-by-trial maximum likelihood, one participant at a time, on about 131
trials. No recovery was reported for it. Two independent reviews of the
manuscript pointed out that the fitted values of the transfer test cannot be
interpreted without one, and that two of its results (the sign of persistence
differing between structures; the spread of the fitted learning rate across
structures) might be what the structures do to ANY data set, not properties of
the participants.

What it does. Synthetic agents are simulated on the target protocol and fitted
with exactly the likelihood, bounds and optimiser of P16 (affect coupling off).
  - Generating structure: each of the six structures in turn.
  - Generating values: the 112 participants' own fitted values under that
    structure (P16, lambda = 0), so the synthetic sample has the same spread,
    bound pile-up and trial counts as the real one.
  - Every synthetic data set is fitted with all six structures.

Because the true values are known, this gives
  A. parameter recovery: true against recovered, for each structure fitted to
     its own data;
  B. cross-fitting: what each structure returns when another one generated the
     data (in particular: fitted persistence when the true persistence is zero,
     and the fitted learning rate when one known rate generated the data);
  C. model recovery: which structure wins by summed BIC and by individual
     count, for each generating structure.

READINGS, fixed before this script was first run on the full sample:
  A. A parameter is "recovered" under a structure if Pearson r between true
     and recovered values is at least 0.7, the threshold the platform's
     recovery analysis used. Below that it is "exploratory" at this trial
     count and individual values under that structure must not be interpreted.
  B1. If, for data generated by the base module (true persistence zero),
     fitted persistence is positive for at least 75 per cent of agents under
     the published structure, or negative for at least 55 per cent under
     base-plus-persistence, the sign of persistence under that structure is
     not a property of the agent and the paper must say so.
  B2. If, for data generated by the base module, the median fitted learning
     rate under the other structures spans a factor of 1.5 or more, the spread
     across structures seen in the participants is at least partly a property
     of the structures.
  C. Summed BIC "recovers" a generating structure if it ranks that structure
     first in every replication. Individual winner counts are "informative"
     only if the generating structure is the individual winner for more than
     half of agents.

The fit never starts from the true values: nine starts drawn by P10's start
generator, the same number P16 used (eight plus one warm start).

SELF-CHECK before anything is fitted: for every simulated agent the
log-likelihood accumulated while generating its choices must equal P16's
likelihood evaluated at the true values on the generated sequence. This
guarantees that the simulator and the fitted model use one update rule.

UNREGISTERED addition, made after the second round of independent review.

Rule 1: every number lands in results/p19_recovery_ml.json.

Usage:  python experiments/p19_recovery_ml.py [--reps 2] [--workers N] [--smoke]
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from multiprocessing import Pool

import numpy as np
from scipy.optimize import minimize

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "src"))

import p10_model_comparison as p10              # noqa: E402
import p13_bounds_sensitivity as p13            # noqa: E402
import p16_split_and_affect_sensitivity as p16  # noqa: E402

RESULTS_DIR = os.path.join(HERE, "..", "results")
LAM0, SPLIT = 0.0, "outcome"
N_STARTS = 9
R_MIN = 0.7
SEED0 = 19000
TOL = 1e-3
READ = {"r_min": R_MIN, "b1_pos_share_M5": 0.75, "b1_neg_share_M2": 0.55,
        "b2_span": 1.5, "c_individual_majority": 0.5}
MODELS = list(p10.ALL_MODELS)


def simulate(P, model, n_trials, seed):
    """Simulate len(P) agents of one structure. Returns choices, rewards and the
    log-likelihood of the generated choices under the generating values."""
    from cpsych.environments.reversal_bandit import ReversalBandit  # as P11
    B = len(P)
    un = [p10._unpack(list(p), model) for p in P]
    a_pos = np.array([u[0] for u in un]); a_neg = np.array([u[1] for u in un])
    beta = np.array([u[2] for u in un]); pers = np.array([u[3] for u in un])
    cf = bool(un[0][4])
    T = int(max(n_trials))
    rng = np.random.default_rng(seed)
    env = ReversalBandit(p_reward=0.75, p_incorrect=0.0,
                         reversal_mode="criterion", criterion_range=(7, 15))
    env.reset(B, rng)
    mask = np.ones(B, dtype=bool)
    V = np.full((B, 2), 0.5)
    prev = np.full(B, -1)
    ch = np.zeros((T, B), dtype=int); rw = np.zeros((T, B))
    ll = np.zeros(B)
    idx = np.arange(B)
    n_trials = np.asarray(n_trials)
    for t in range(T):
        env.next_trial(rng, mask)
        logit = beta * (V[:, 1] - V[:, 0])
        logit = logit + np.where(prev >= 0, pers * (2.0 * prev - 1.0), 0.0)
        logit = np.clip(logit, -50.0, 50.0)
        p1 = 1.0 / (1.0 + np.exp(-logit))
        c = (rng.random(B) < p1).astype(int)
        r = np.asarray(env.reward(c.astype(float), rng)["r"], dtype=float)
        p = np.where(c == 1, p1, 1.0 - p1)
        ll += np.where(t < n_trials, np.log(np.maximum(p, 1e-12)), 0.0)
        delta = r - V[idx, c]
        rate = np.where(r > 0.5, a_pos, a_neg)
        V[idx, c] += rate * delta
        if cf:
            u = 1 - c
            r_cf = 1.0 - r
            rate_cf = np.where(r_cf > 0.5, a_pos, a_neg)
            V[idx, u] += rate_cf * (r_cf - V[idx, u])
        prev = c
        ch[t] = c; rw[t] = r
    return ([ch[:n_trials[b], b].copy() for b in range(B)],
            [rw[:n_trials[b], b].copy() for b in range(B)], ll)


def fit_one(task):
    """Fit one structure to one synthetic agent. Never starts from the truth."""
    key, choice, reward, model, seed = task
    rng = np.random.default_rng(seed)
    bnds = p13.bounds_new(model)
    best = None
    for x0 in p10.starts(model, rng, n=N_STARTS):
        x0 = [min(max(v, lo), hi) for v, (lo, hi) in zip(x0, bnds)]
        try:
            res = minimize(p16.nll, x0, args=(choice, reward, model, LAM0, SPLIT),
                           method="L-BFGS-B", bounds=bnds)
        except Exception:
            continue
        if np.isfinite(res.fun) and (best is None or res.fun < best.fun):
            best = res
    if best is None:
        return key, None, float("nan"), float("nan")
    n = choice.size
    return (key, [float(v) for v in best.x], float(best.fun),
            float(p10.N_PARAMS[model] * np.log(n) + 2.0 * best.fun))


def corr(x, y):
    x, y = np.asarray(x, float), np.asarray(y, float)
    if x.std() == 0 or y.std() == 0:
        return float("nan")
    return float(np.corrcoef(x, y)[0, 1])


def spearman(x, y):
    rx = np.argsort(np.argsort(x)).astype(float)
    ry = np.argsort(np.argsort(y)).astype(float)
    return corr(rx, ry)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=2)
    ap.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    ap.add_argument("--smoke", action="store_true",
                    help="12 agents, 1 replication: checks that the script runs")
    args = ap.parse_args()

    with open(os.path.join(RESULTS_DIR,
                           "p16_split_and_affect_sensitivity.json")) as f:
        p16j = json.load(f)
    assert not p16j["smoke_run"]
    per = {m: p16j["per_subject"][m + "_lam0"] for m in MODELS}
    ids = [f["id"] for f in per["M1"]]
    for m in MODELS:
        assert [f["id"] for f in per[m]] == ids
    n_agents = 12 if args.smoke else len(ids)
    reps = 1 if args.smoke else args.reps
    n_trials = [per["M1"][i]["n_trials"] for i in range(n_agents)]
    names = {m: list(p10.PARAM_NAMES[m]) for m in MODELS}
    print(f"agents {n_agents}, replications {reps}, workers {args.workers}, "
          f"starts {N_STARTS}, lambda {LAM0}")

    # ---- simulate, with the self-check
    truth, data, worst = {}, {}, 0.0
    for gi, g in enumerate(MODELS):
        truth[g] = np.array([per[g][i]["params"] for i in range(n_agents)])
        for rep in range(reps):
            ch, rw, ll = simulate(truth[g], g, n_trials, SEED0 + 100 * gi + rep)
            for b in range(n_agents):
                v = p16.nll(list(truth[g][b]), ch[b], rw[b], g, LAM0, SPLIT)
                worst = max(worst, abs(v + ll[b]))
            data[(g, rep)] = (ch, rw)
    print(f"self-check, simulator against the fitted likelihood: {worst:.2e}")
    assert worst < 1e-8, "the simulator and the likelihood use different rules"

    # ---- fit every structure to every data set
    tasks = []
    for gi, g in enumerate(MODELS):
        for rep in range(reps):
            ch, rw = data[(g, rep)]
            for fi, m in enumerate(MODELS):
                for b in range(n_agents):
                    seed = SEED0 + 1_000_000 * (gi * 6 + fi) + 10_000 * rep + b
                    tasks.append(((g, rep, m, b), ch[b], rw[b], m, seed))
    print(f"fits to run: {len(tasks)}")
    t0 = time.time()
    out = {}
    with Pool(args.workers) as pool:
        for k, res in enumerate(pool.imap_unordered(fit_one, tasks, chunksize=8)):
            out[res[0]] = res[1:]
            if (k + 1) % 500 == 0:
                el = time.time() - t0
                print(f"  {k+1}/{len(tasks)}  {el/60:.1f} min elapsed, "
                      f"about {el/(k+1)*(len(tasks)-k-1)/60:.0f} min left")
    n_failed = sum(1 for v in out.values() if v[0] is None)
    print(f"done in {(time.time()-t0)/60:.1f} min; failed fits: {n_failed}")

    def rec(g, rep, m):
        return np.array([out[(g, rep, m, b)][0] for b in range(n_agents)])

    def bic(g, rep, m):
        return np.array([out[(g, rep, m, b)][2] for b in range(n_agents)])

    # ---- A. parameter recovery, own structure
    part_a = {}
    print("\nA. Parameter recovery (structure fitted to its own data)")
    for g in MODELS:
        T = np.vstack([truth[g]] * reps)
        Rc = np.vstack([rec(g, rep, g) for rep in range(reps)])
        e = {}
        for j, nm in enumerate(names[g]):
            lo, hi = p13.bounds_new(g)[j]
            e[nm] = {"pearson_r": corr(T[:, j], Rc[:, j]),
                     "spearman_r": spearman(T[:, j], Rc[:, j]),
                     "true_median": float(np.median(T[:, j])),
                     "recovered_median": float(np.median(Rc[:, j])),
                     "median_error": float(np.median(Rc[:, j] - T[:, j])),
                     "median_abs_error": float(np.median(np.abs(Rc[:, j] - T[:, j]))),
                     "share_recovered_at_bound": float(np.mean(
                         (Rc[:, j] <= lo + TOL) | (Rc[:, j] >= hi - TOL))),
                     "share_true_at_bound": float(np.mean(
                         (T[:, j] <= lo + TOL) | (T[:, j] >= hi - TOL))),
                     "recovered": bool(corr(T[:, j], Rc[:, j]) >= R_MIN)}
            if nm == "persistence":
                e[nm]["share_sign_correct"] = float(np.mean(
                    np.sign(Rc[:, j]) == np.sign(T[:, j])))
            print(f"  {g} {nm:12s} r {e[nm]['pearson_r']:6.3f}  rho "
                  f"{e[nm]['spearman_r']:6.3f}  median {e[nm]['true_median']:7.3f} -> "
                  f"{e[nm]['recovered_median']:7.3f}  "
                  f"{'recovered' if e[nm]['recovered'] else 'EXPLORATORY'}")
        part_a[g] = e

    # ---- B. cross-fitting
    part_b = {}
    print("\nB. Cross-fitting: median fitted values, generating structure in rows")
    for g in MODELS:
        part_b[g] = {"true_median": {nm: float(np.median(truth[g][:, j]))
                                     for j, nm in enumerate(names[g])}}
        for m in MODELS:
            Rc = np.vstack([rec(g, rep, m) for rep in range(reps)])
            e = {nm: {"median": float(np.median(Rc[:, j])),
                      "iqr": [float(np.percentile(Rc[:, j], 25)),
                              float(np.percentile(Rc[:, j], 75))]}
                 for j, nm in enumerate(names[m])}
            if "persistence" in names[m]:
                x = Rc[:, names[m].index("persistence")]
                e["persistence"].update(share_negative=float(np.mean(x < 0)),
                                        share_positive=float(np.mean(x > 0)))
            part_b[g][m] = e
        print(f"  generated by {g}: " + "  ".join(
            f"{m} " + "/".join(f"{part_b[g][m][nm]['median']:.2f}"
                               for nm in names[m] if nm.startswith("alpha"))
            for m in MODELS))
    b1_m5 = part_b["M1"]["M5"]["persistence"]["share_positive"]
    b1_m2 = part_b["M1"]["M2"]["persistence"]["share_negative"]
    lr_m1 = [part_b["M1"][m][nm]["median"] for m in MODELS for nm in names[m]
             if nm.startswith("alpha")]
    span = float(max(lr_m1) / min(lr_m1))
    print(f"  true persistence zero (base module data): positive under the published "
          f"structure for {100*b1_m5:.0f}%, negative under base-plus-persistence for "
          f"{100*b1_m2:.0f}%")
    print(f"  one generating learning rate (base module data): fitted medians span "
          f"a factor of {span:.2f}")

    # ---- C. model recovery
    part_c = {}
    print("\nC. Model recovery: generating structure in rows")
    for g in MODELS:
        winners_sum, counts = [], np.zeros(len(MODELS), dtype=int)
        sums = []
        for rep in range(reps):
            Bm = np.array([bic(g, rep, m) for m in MODELS])
            s = Bm.sum(axis=1)
            sums.append([float(v) for v in s])
            winners_sum.append(MODELS[int(np.argmin(s))])
            for w in Bm.argmin(axis=0):
                counts[w] += 1
        share_own = float(counts[MODELS.index(g)] / counts.sum())
        part_c[g] = {"summed_bic_winner_per_replication": winners_sum,
                     "summed_bic_per_replication": sums,
                     "summed_bic_recovers": bool(all(w == g for w in winners_sum)),
                     "individual_winner_counts": {m: int(c) for m, c in zip(MODELS, counts)},
                     "share_individual_winner_is_generator": share_own,
                     "individual_counts_informative": bool(
                         share_own > READ["c_individual_majority"])}
        print(f"  {g}: summed BIC picks {winners_sum}; individual winners "
              f"{dict(zip(MODELS, counts.tolist()))}")

    reading = {
        "A_exploratory": [f"{g}.{nm}" for g in MODELS for nm in names[g]
                          if not part_a[g][nm]["recovered"]],
        "A_recovered": [f"{g}.{nm}" for g in MODELS for nm in names[g]
                        if part_a[g][nm]["recovered"]],
        "B1_share_positive_M5_when_true_zero": b1_m5,
        "B1_share_negative_M2_when_true_zero": b1_m2,
        "B1_sign_under_M5_not_a_property_of_agent": bool(b1_m5 >= READ["b1_pos_share_M5"]),
        "B1_sign_under_M2_not_a_property_of_agent": bool(b1_m2 >= READ["b1_neg_share_M2"]),
        "B2_learning_rate_span_when_one_true_rate": span,
        "B2_spread_partly_structural": bool(span >= READ["b2_span"]),
        "C_summed_bic_recovers_all": bool(all(part_c[g]["summed_bic_recovers"]
                                              for g in MODELS)),
        "C_summed_bic_fails_for": [g for g in MODELS
                                   if not part_c[g]["summed_bic_recovers"]],
        "C_individual_counts_informative_for": [
            g for g in MODELS if part_c[g]["individual_counts_informative"]],
    }
    print()
    for k, v in reading.items():
        print(f"{k}: {v}")

    result = {
        "procedure": "parameter and model recovery for per-participant maximum "
                     "likelihood on the target protocol, affect coupling off; "
                     "generating values are the participants' fitted values (P16)",
        "registered": False,
        "smoke_run": bool(args.smoke),
        "lambda": LAM0, "split": SPLIT,
        "n_agents": n_agents, "n_replications": reps, "n_starts": N_STARTS,
        "trial_counts": {"min": int(min(n_trials)), "max": int(max(n_trials)),
                         "median": float(np.median(n_trials))},
        "seed0": SEED0,
        "reading_thresholds": READ,
        "self_check_max_abs_diff": float(worst),
        "n_fits": len(tasks), "n_failed_fits": int(n_failed),
        "A_parameter_recovery": part_a,
        "B_cross_fitting": part_b,
        "C_model_recovery": part_c,
        "reading": reading,
        "per_fit": {f"{g}|{rep}|{m}": {"params": [out[(g, rep, m, b)][0]
                                                   for b in range(n_agents)],
                                         "bic": [out[(g, rep, m, b)][2]
                                                 for b in range(n_agents)]}
                    for g in MODELS for rep in range(reps) for m in MODELS},
        "truth": {g: truth[g].tolist() for g in MODELS},
    }
    name = "p19_recovery_ml_smoke.json" if args.smoke else "p19_recovery_ml.json"
    path = os.path.join(RESULTS_DIR, name)
    with open(path, "w") as f:
        json.dump(result, f, indent=1)
    print(f"\nSaved to {path}")


if __name__ == "__main__":
    main()
