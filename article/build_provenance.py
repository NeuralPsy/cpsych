"""Generate provenance.md from numbers.json.

Every number in the paper traces to a results/ file.
Run after build_numbers.py.

Usage: python article/build_provenance.py
"""
import json
from pathlib import Path
from collections import defaultdict

ROOT = Path(__file__).resolve().parent.parent
NUMBERS = ROOT / "article" / "numbers.json"
OUT = ROOT / "article" / "provenance.md"


def main():
    with open(NUMBERS) as f:
        numbers = json.load(f)

    # Group by source file
    by_source = defaultdict(list)
    for name, entry in numbers.items():
        by_source[entry["source"]].append((name, entry))

    lines = [
        "# Provenance",
        "",
        "Auto-generated by `build_provenance.py` from `numbers.json`.",
        f"Total numbers: {len(numbers)}.",
        "",
        "## Numbers by source file",
        "",
    ]

    for source in sorted(by_source.keys()):
        entries = by_source[source]
        lines.append(f"### `results/{source}`")
        lines.append("")
        lines.append("| Key | Value | Path | Description |")
        lines.append("|-----|------:|------|-------------|")
        for name, entry in sorted(entries, key=lambda x: x[0]):
            val = entry["value"]
            if isinstance(val, float):
                val_str = f"{val:.4f}" if abs(val) < 100 else f"{val:.1f}"
            elif isinstance(val, bool):
                val_str = str(val)
            else:
                val_str = str(val)
            path = entry.get("path", "—")
            desc = entry.get("desc", "")
            lines.append(f"| {name} | {val_str} | {path} | {desc} |")
        lines.append("")

    lines.extend([
        "## Data provenance",
        "",
        "| Dataset | Source | Manifest | License |",
        "|---------|--------|----------|---------|",
        "| Confidence Database | osf.io/s46pr | manifest_confidence_db.json | CC-By 4.0 |",
        "| OBF-Psychiatric | zenodo.org/13754984 | manifest_obf_psychiatric.json | CC BY 4.0 |",
        "| Eckstein 2022 | osf.io/7wuh4 + h4qr6 | manifest_eckstein2022.json | CC-By 4.0 |",
        "",
        "Data files in `.gitignore`. SHA-256 checksums in manifests.",
        "",
        "## Revisions post-factum",
        "",
        "| ID | What | When |",
        "|----|------|------|",
        "| D17 | coh=0 criterion: significance -> effect size | P2.3 |",
        "| D34 | Scout test parameter choice | P4 |",
        "| D45 | Accuracy threshold: single SD -> per-level | P6 |",
        "",
        "## Verification",
        "",
        "`python article/verify_numbers.py` checks every entry against its source file.",
        f"Last run: {len(numbers)}/{len(numbers)} verified.",
    ])

    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Generated {OUT} ({len(numbers)} numbers, "
          f"{len(by_source)} source files)")


if __name__ == "__main__":
    main()
