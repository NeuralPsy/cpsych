#!/usr/bin/env python3
"""Print the numbers of P19 and P20 straight from the result files.

P19: parameter and model recovery for per-participant maximum likelihood on
     the second task, on synthetic agents with known parameters.
P20: the same agents fitted with the affect coupling wrongly fixed at 0.49.

Usage:  python article/report_p19_p20.py results
"""
import json
import os
import sys

R = sys.argv[1] if len(sys.argv) > 1 else "results"


def load(name):
    with open(os.path.join(R, name), encoding="utf-8") as f:
        return json.load(f)


p19 = load("p19_recovery_ml.json")
p20 = load("p20_fixed_term_bias.json")
NAMES = {"M1": "base", "M2": "base + persistence", "M3": "separate rates",
         "M4": "separate rates + persistence", "M5": "published structure",
         "M6": "counterfactual only"}

print("=" * 78)
print("P19  recovery on synthetic agents with known parameters")
print("=" * 78)
print(f"agents {p19['n_agents']}, replications {p19['n_replications']}, starts "
      f"{p19['n_starts']}, trials {p19['trial_counts']}, fits {p19['n_fits']}, "
      f"failed {p19['n_failed_fits']}, self-check {p19['self_check_max_abs_diff']:.1e}")

print("\nA. Parameter recovery (generating structure fitted)")
for g, e in p19["A_parameter_recovery"].items():
    for nm, v in e.items():
        print(f"  {g} {NAMES[g]:30s} {nm:12s} r {v['pearson_r']:6.3f}  rho "
              f"{v['spearman_r']:6.3f}  median {v['true_median']:7.3f} -> "
              f"{v['recovered_median']:7.3f}  "
              f"{'recovered' if v['recovered'] else 'exploratory'}")

print("\nB. Cross-fitting: medians returned by each fitted structure")
for g, e in p19["B_cross_fitting"].items():
    print(f"  generated by {g} {NAMES[g]}; true medians "
          f"{ {k: round(v, 3) for k, v in e['true_median'].items()} }")
    for m in NAMES:
        parts = []
        for nm, v in e[m].items():
            s = f"{nm} {v['median']:.3f}"
            if "share_negative" in v:
                s += (f" (negative {100 * v['share_negative']:.0f}%, positive "
                      f"{100 * v['share_positive']:.0f}%)")
            parts.append(s)
        print(f"      fitted {m}: " + "; ".join(parts))

print("\nC. Model recovery")
for g, e in p19["C_model_recovery"].items():
    print(f"  {g} {NAMES[g]:30s} summed BIC picks "
          f"{e['summed_bic_winner_per_replication']}; individual winners "
          f"{e['individual_winner_counts']}; generator is best fit for "
          f"{100 * e['share_individual_winner_is_generator']:.0f}%")

print("\nReading")
for k, v in p19["reading"].items():
    print(f"  {k}: {v}")

print()
print("=" * 78)
print("P20  affect coupling wrongly fixed at "
      f"{p20['lambda_fitted']} for agents generated with it off")
print("=" * 78)
print(f"fits {p20['n_fits']}, failed {p20['n_failed_fits']}, self-check "
      f"{p20['self_check_max_abs_diff']:.1e}")
for g, e in p20["models"].items():
    print(f"  {g} {NAMES[g]}: summed NLL off {[round(v, 1) for v in e['nll_sum_off_per_replication']]}"
          f"  on {[round(v, 1) for v in e['nll_sum_on_per_replication']]}")
    for nm, v in e["parameters"].items():
        print(f"      {nm:12s} true {v['true_median']:7.3f}  off "
              f"{v['median_coupling_off']:7.3f}  on {v['median_coupling_on']:7.3f}  "
              f"shift {v['shift_on_minus_off']:+.3f}  "
              f"{'biased' if v['biased_by_fixed_term'] else 'unchanged'}")
print("\nReading")
for k, v in p20["reading"].items():
    print(f"  {k}: {v}")
