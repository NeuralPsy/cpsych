#!/usr/bin/env python3
"""Draw the three figures of the transfer test straight from the result files.

Nothing is recomputed: every point is read from results/*.json, and every
count printed on a figure is counted from those points.

Figure 1  Fitted learning rates under six model structures (P16, lambda = 0),
          with the medians the same structures return for simulated agents
          generated by the base module (P19).
Figure 2  Participants (left) beside simulated agents with known values (right).
          (A, B) Choice persistence under two structures (P16; P19).
          (C, D) One learning rate with the affect coupling off and on
          (P16 and P13; P19 and P20).
Figure 3  Behaviour simulated at calibrated and fitted values against the
          observed data (P18, 200 seeds).

Usage:  python article/make_figures.py results article/figures
Writes  figure1.pdf/.png, figure2.pdf/.png, figure3.pdf/.png  (PNG at 600 dpi)
"""
import json
import os
import sys

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = sys.argv[1] if len(sys.argv) > 1 else "results"
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join("article", "figures")
os.makedirs(OUT, exist_ok=True)

BLUE, ORANGE = "#2a78d6", "#eb6834"
INK, INK2, GRID = "#0b0b0b", "#52514e", "#d9d8d3"
plt.rcParams.update({
    "font.family": "DejaVu Sans", "font.size": 8, "axes.edgecolor": INK2,
    "axes.linewidth": 0.6, "axes.labelcolor": INK, "xtick.color": INK2,
    "ytick.color": INK2, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
    "axes.spines.top": False, "axes.spines.right": False,
    "pdf.fonttype": 42, "savefig.facecolor": "white", "figure.facecolor": "white",
})


def load(name):
    with open(os.path.join(R, name), encoding="utf-8") as f:
        return json.load(f)


def save(fig, stem):
    for ext, kw in (("pdf", {}), ("png", {"dpi": 600})):
        fig.savefig(os.path.join(OUT, f"{stem}.{ext}"), bbox_inches="tight", **kw)
    plt.close(fig)
    print("written", os.path.join(OUT, stem + ".pdf"), "and .png")


p13 = load("p13_bounds_sensitivity.json")
p16 = load("p16_split_and_affect_sensitivity.json")
p18 = load("p18_transfer_lambda0.json")
p19 = load("p19_recovery_ml.json")
p20 = load("p20_fixed_term_bias.json")
assert not p19["smoke_run"] and not p20["smoke_run"]
assert not p16["smoke_run"] and p18["lambda"] == 0.0 and p18["n_seeds"] == 200
N = p18["n_subjects"]
PN = {m: v["param_names"] for m, v in p16["check2_lambda_zero"]["models"].items()}


def lam0(model, name):
    i = PN[model].index(name)
    return np.array([s["params"][i] for s in p16["per_subject"][model + "_lam0"]])


def lam049(model, name):
    i = p13["models"][model]["wide_bounds"]["param_names"].index(name)
    return np.array([s["params"][i] for s in p13["per_subject_wide"][model]])


ids0 = [s["id"] for s in p16["per_subject"]["M5_lam0"]]
assert ids0 == [s["id"] for s in p16["per_subject"]["M2_lam0"]]
assert ids0 == [s["id"] for s in p13["per_subject_wide"]["M5"]], "participant order differs"

rng = np.random.default_rng(0)          # jitter only; no data depend on it

# =========================================================== Figure 1
rows = [("Base module", "M1", "alpha", "α"),
        ("Base + persistence", "M2", "alpha", "α"),
        ("Separate rates", "M3", "alpha_pos", "α⁺"),
        ("Separate rates", "M3", "alpha_neg", "α⁻"),
        ("Separate rates + persistence", "M4", "alpha_pos", "α⁺"),
        ("Separate rates + persistence", "M4", "alpha_neg", "α⁻"),
        ("Counterfactual revision only", "M6", "alpha", "α"),
        ("Published structure", "M5", "alpha_pos", "α⁺"),
        ("Published structure", "M5", "alpha_neg", "α⁻")]
fig, ax = plt.subplots(figsize=(6.9, 4.3))
ax.axvspan(0.01, 0.50, color="#f0efec", zorder=0, lw=0)
for x, lab, ha, dx in ((0.15, "calibrated\n0.15", "center", 0),
                       (0.50, "declared\nmaximum 0.50", "center", 0),
                       (0.99, "optimiser\nbound 0.99", "right", 0.012)):
    ax.axvline(x, color=INK2, lw=0.7, ls=(0, (3, 2)) if x != 0.15 else "-", zorder=1)
    ax.text(x + dx, len(rows) - 0.35, lab, ha=ha, va="bottom", fontsize=6.5, color=INK2,
            linespacing=1.05)
ylabels = []
for k, (name, m, par, sym) in enumerate(rows):
    y = len(rows) - 1 - k
    x = lam0(m, par)
    ax.scatter(x, y + rng.uniform(-0.28, 0.28, x.size), s=7, color=BLUE, alpha=0.45,
               lw=0, zorder=2)
    q1, med, q3 = np.percentile(x, [25, 50, 75])
    ax.plot([q1, q3], [y, y], color=INK, lw=2.2, solid_capstyle="butt", zorder=3)
    ax.plot([med], [y], marker="o", ms=5.5, mfc="white", mec=INK, mew=1.3, zorder=4)
    syn = p19["B_cross_fitting"]["M1"][m][par]["median"]
    ax.plot([syn], [y - 0.36], marker="D", ms=4.6, mfc=ORANGE, mec="white", mew=0.6,
            zorder=5, ls="")
    ax.text(1.045, y, f"{med:.2f}", va="center", ha="left", fontsize=7.5, color=INK)
    ax.text(1.135, y, f"×{med / 0.15:.1f}", va="center", ha="left", fontsize=7.5, color=INK2)
    ax.text(1.225, y, f"{int((x >= 0.99 - 1e-3).sum())}", va="center", ha="left",
            fontsize=7.5, color=INK2)
    ylabels.append(f"{name}   {sym}")
for xx, lab in ((1.045, "median"), (1.135, "× calib."), (1.225, "at bound")):
    ax.text(xx, len(rows) - 0.35, lab, ha="left", va="bottom", fontsize=6.5, color=INK2)
ax.set_yticks(range(len(rows) - 1, -1, -1))
ax.set_yticklabels(ylabels, color=INK)
ax.tick_params(axis="y", length=0)
ax.set_ylim(-0.6, len(rows) - 0.4)
ax.set_xlim(0, 1.0)
ax.set_xticks([0, 0.15, 0.25, 0.50, 0.75, 0.99])
ax.set_xticklabels(["0", "0.15", "0.25", "0.50", "0.75", "0.99"])
ax.set_xlabel(f"Fitted learning rate (one dot per participant, n = {N})")
ax.spines["left"].set_visible(False)
true_a = p19["B_cross_fitting"]["M1"]["true_median"]["alpha"]
ax.axvline(true_a, color=ORANGE, lw=0.9, ls=":", zorder=0)
h1 = [plt.Line2D([], [], marker="o", ls="", ms=4, mfc=BLUE, mec="none", alpha=0.6,
                 label="participant"),
      plt.Line2D([], [], marker="o", ls="-", color=INK, lw=2.2, ms=5.5, mfc="white", mec=INK,
                 mew=1.3, label="participants: median, interquartile range"),
      plt.Line2D([], [], marker="D", ls="", ms=4.6, mfc=ORANGE, mec="white", mew=0.6,
                 label="simulated agents: median returned"),
      plt.Line2D([], [], color=ORANGE, lw=0.9, ls=":",
                 label=f"simulated agents: true median rate, {true_a:.2f}")]
fig.legend(handles=h1, loc="lower center", ncol=2, frameon=False, fontsize=7,
           bbox_to_anchor=(0.5, -0.07), handlelength=1.8, columnspacing=1.6)
save(fig, "figure1")

# =========================================================== Figure 2
def syn(gen, fit_model, name):
    i = PN[fit_model].index(name)
    return np.concatenate([np.array(p19["per_fit"][f"{gen}|{r}|{fit_model}"]["params"])[:, i]
                           for r in range(p19["n_replications"])])


def syn_on(gen, name):
    i = PN[gen].index(name)
    return np.concatenate([np.array(p20["per_fit_on"][f"{gen}|{r}"])[:, i]
                           for r in range(p20["n_replications"])])


def persistence_panel(a, px, py, letter, title):
    a.set_xscale("symlog", linthresh=1.0, linscale=1.0)
    a.set_yscale("symlog", linthresh=1.0, linscale=1.0)
    a.axhline(0, color=INK2, lw=0.7, zorder=1)
    a.axvline(0, color=INK2, lw=0.7, zorder=1)
    a.scatter(px, py, s=9, color=BLUE, alpha=0.5, lw=0, zorder=2)
    a.set_xlim(-25, 25); a.set_ylim(-25, 25)
    ticks = [-20, -5, -1, 0, 1, 5, 20]
    a.set_xticks(ticks); a.set_yticks(ticks)
    a.set_xticklabels([str(t) for t in ticks]); a.set_yticklabels([str(t) for t in ticks])
    a.minorticks_off()
    n = px.size
    a.text(0.97, 0.04, f"negative on x: {int((px < 0).sum())} of {n}\n"
                       f"positive on y: {int((py > 0).sum())} of {n}",
           transform=a.transAxes, ha="right", va="bottom", fontsize=6.5, color=INK,
           linespacing=1.2)
    a.set_xlabel("Persistence, base + persistence")
    a.set_ylabel("Persistence, published structure")
    a.set_box_aspect(1)
    a.set_title(letter, loc="left", fontsize=10, fontweight="bold", color=INK, pad=16)
    a.text(0.12, 1.045, title, transform=a.transAxes, ha="left", va="bottom", fontsize=7.5,
           color=INK)


def rate_panel(b, x0, x1, letter, title, truth=None):
    b.plot([0, 1], [0, 1], color=INK2, lw=0.7, ls=(0, (3, 2)), zorder=1)
    b.scatter(x0, x1, s=9, color=BLUE, alpha=0.5, lw=0, zorder=2)
    m0, m1 = float(np.median(x0)), float(np.median(x1))
    b.plot([m0], [m1], marker="o", ms=7, mfc="white", mec=INK, mew=1.4, zorder=4)
    b.text(0.60, 0.635, "no change", ha="center", va="bottom", fontsize=6.5, color=INK2,
           rotation=45, rotation_mode="anchor")
    b.set_xlim(0, 1.02); b.set_ylim(0, 1.02)
    b.set_box_aspect(1)
    tk = [0, 0.25, 0.5, 0.75, 0.99]
    b.set_xticks(tk); b.set_yticks(tk)
    b.set_xticklabels(["0", "0.25", "0.50", "0.75", "0.99"])
    b.set_yticklabels(["0", "0.25", "0.50", "0.75", "0.99"])
    b.set_xlabel("α⁺, published structure, coupling off")
    b.set_ylabel("α⁺, published structure, coupling on")
    extra = "" if truth is None else f"; true median {truth:.2f}"
    b.text(0.03, 0.97, f"medians {m0:.2f} → {m1:.2f}{extra}\nlower with coupling on: "
                       f"{int((x1 < x0 - 1e-9).sum())} of {x0.size}",
           transform=b.transAxes, ha="left", va="top", fontsize=6.5, color=INK,
           linespacing=1.2, bbox=dict(fc="white", ec="none", alpha=0.8, pad=1.5))
    b.set_title(letter, loc="left", fontsize=10, fontweight="bold", color=INK, pad=16)
    b.text(0.12, 1.045, title, transform=b.transAxes, ha="left", va="bottom", fontsize=7.5,
           color=INK)
    return m0, m1


fig, ax4 = plt.subplots(2, 2, figsize=(6.9, 7.2), gridspec_kw={"wspace": 0.36, "hspace": 0.42})
px, py = lam0("M2", "persistence"), lam0("M5", "persistence")
persistence_panel(ax4[0, 0], px, py, "A", "Participants")
sx, sy = syn("M1", "M2", "persistence"), syn("M1", "M5", "persistence")
persistence_panel(ax4[0, 1], sx, sy, "B", "Simulated agents with no persistence")
x0, x1 = lam0("M5", "alpha_pos"), lam049("M5", "alpha_pos")
m0, m1 = rate_panel(ax4[1, 0], x0, x1, "C", "Participants")
s0, s1 = syn("M5", "M5", "alpha_pos"), syn_on("M5", "alpha_pos")
t5 = float(np.median(np.array(p19["truth"]["M5"])[:, PN["M5"].index("alpha_pos")]))
rate_panel(ax4[1, 1], s0, s1, "D", "Simulated agents, coupling truly off", truth=t5)
save(fig, "figure2")
nx, ny = int((px < 0).sum()), int((py > 0).sum())
both = int(((px < 0) & (py > 0)).sum())
below = int((x1 < x0 - 1e-9).sum())

# =========================================================== Figure 3
B = p18["part_b_behaviour"]
O = p18["observed"]
conds = [("Calibrated values", None, None),
         ("Base module", "K1_calibrated_base", "cal"),
         ("Base + persistence", "K2_calibrated_plus_persistence", "cal"),
         ("Counterfactual revision only", "K6_calibrated_counterfactual_only", "cal"),
         ("Published structure", "K5_calibrated_published_model", "cal"),
         ("Freely fitted values", None, None),
         ("Base module", "C_freefit_per_subject_base", "fit"),
         ("Base + persistence", "D_freefit_per_subject_persistence", "fit"),
         ("Separate rates", "G_freefit_per_subject_valence_split", "fit"),
         ("Separate rates + persistence", "H_freefit_per_subject_valence_split_persistence", "fit"),
         ("Counterfactual revision only", "F_freefit_per_subject_counterfactual_only", "fit"),
         ("Published structure", "E_freefit_per_subject_published_model", "fit")]
panels = [("ws", "Win-stay"), ("ls", "Lose-shift"), ("acc", "Accuracy")]
fig, axes = plt.subplots(1, 3, figsize=(6.9, 3.9), sharey=True,
                         gridspec_kw={"wspace": 0.10})
n = len(conds)
for ax, (k, title) in zip(axes, panels):
    lo, hi = O[k]["iqr"]
    mu, se = O[k]["mean"], O[k]["se"]
    ax.axvspan(lo, hi, color="#e4e3de", lw=0, zorder=0)
    ax.axvspan(mu - 2 * se, mu + 2 * se, color="#b9b8b2", lw=0, zorder=1)
    ax.axvline(mu, color=INK, lw=0.9, zorder=2)
    for i, (lab, key, kind) in enumerate(conds):
        y = n - 1 - i
        if key is None:
            continue
        c = B[key][k]
        ok = c["within_2se"]
        col = ORANGE if kind == "cal" else BLUE
        ax.plot([c["mean"]], [y], marker="s" if kind == "cal" else "o", ms=5.5,
                mfc=col if ok else "white", mec=col, mew=1.4, zorder=4, ls="")
        ax.plot([mu, c["mean"]], [y, y], color=col, lw=0.6, alpha=0.6, zorder=3)
    ax.set_title(title, fontsize=8.5, color=INK, pad=5)
    ax.set_ylim(-0.7, n - 0.3)
    ax.tick_params(axis="y", length=0)
    ax.grid(axis="x", color=GRID, lw=0.4, zorder=-1)
    ax.set_axisbelow(True)
    ax.spines["left"].set_visible(False)
    ax.set_xlabel("proportion of trials")
axes[0].set_yticks([n - 1 - i for i in range(n)])
axes[0].set_yticklabels([c[0] for c in conds])
for tick, (lab, key, kind) in zip(axes[0].get_yticklabels(), conds):
    tick.set_color(INK)
    if key is None:
        tick.set_fontweight("bold")
axes[0].set_xlim(0.62, 1.01)
axes[1].set_xlim(0.28, 0.74)
axes[2].set_xlim(0.55, 0.80)
h = [plt.Line2D([], [], marker="s", ls="", ms=5.5, mfc=ORANGE, mec=ORANGE, label="calibrated values"),
     plt.Line2D([], [], marker="o", ls="", ms=5.5, mfc=BLUE, mec=BLUE, label="freely fitted values"),
     plt.Line2D([], [], marker="o", ls="", ms=5.5, mfc="white", mec=INK2, mew=1.4,
                label="open: outside two SE of observed mean"),
     plt.Line2D([], [], color=INK, lw=0.9, label="observed mean"),
     plt.Rectangle((0, 0), 1, 1, fc="#b9b8b2", ec="none", label="observed mean ± 2 SE"),
     plt.Rectangle((0, 0), 1, 1, fc="#e4e3de", ec="none", label="observed interquartile range")]
fig.legend(handles=h, loc="lower center", ncol=3, frameon=False, fontsize=7,
           bbox_to_anchor=(0.5, -0.10), handlelength=1.6, columnspacing=1.6)
save(fig, "figure3")

# ---- the counts printed on the figures, for the record
print(f"Figure 2A: persistence negative under base + persistence for {nx} of {N}; "
      f"positive under the published structure for {ny}; both for {both}")
print(f"Figure 2C: medians {m0:.3f} (lambda 0) and {m1:.3f} (lambda 0.49); "
      f"lower with the coupling on for {below} of {N}")
